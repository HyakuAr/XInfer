inline constexpr size_t NUM_UNICODE_RANGES = sizeof(UNICODE_RANGES) / sizeof(UNICODE_RANGES[0]);

inline uint8_t get_unicode_category(uint32_t cp) noexcept {
    if (cp < 128) {
        return ASCII_CATEGORIES[cp];
    }
    if (cp >= 0x110000) {
        return CAT_OTHER;
    }
    // Binary search in sorted ranges
    auto it = std::upper_bound(UNICODE_RANGES, UNICODE_RANGES + NUM_UNICODE_RANGES, cp,
        [](uint32_t val, const UnicodeRange& r) {
            return val < r.first;
        });
    if (it != UNICODE_RANGES) {
        --it;
        if (cp >= it->first && cp <= it->last) {
            return it->cat;
        }
    }
    return CAT_OTHER;
}

